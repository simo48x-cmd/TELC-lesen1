function buildSBTopic(
  id: string,
  part: 'SB1' | 'SB2',
  titleDe: string,
  titleAr: string,
  answers: [string, string, string, string, string, string, string, string, string, string],
  triggers: [string, string, string, string, string, string, string, string, string, string],
  rulesAr: [string, string, string, string, string, string, string, string, string, string]
): SprachbausteinTopic {
  const startNum = part === 'SB1' ? 21 : 31;
  const gaps: SprachbausteinGap[] = answers.map((ans, idx) => {
    const gapNum = startNum + idx;
    const alt1 = part === 'SB1' ? (ans === 'denn' ? 'weil' : 'obwohl') : 'DARÜBER';
    const alt2 = part === 'SB1' ? (ans === 'trotzdem' ? 'deshalb' : 'damit') : 'DESWEGEN';
    const opts = Array.from(new Set([ans, alt1, alt2]));
    while (opts.length < 3) {
      opts.push(opts.length === 1 ? 'jedoch' : 'während');
    }
    return {
      gapNumber: gapNum,
      contextDe: `... ${triggers[idx]} [${gapNum}: ___] ...`,
      contextAr: `الفراغ ${gapNum}: قرينة الجملة هي «${triggers[idx]}»  الجواب الصحيح: ${ans}`,
      correctAnswer: ans,
      options: opts,
      ruleExplanationAr: rulesAr[idx],
      triggerWord: triggers[idx],
    };
  });

  return {
    id,
    part,
    titleDe,
    titleAr,
    codeSummary: answers.join(' · '),
    introTextDe:
      part === 'SB1'
        ? `Lesen Sie den folgenden Brief / die E-Mail zum Thema „${titleDe}“ und entscheiden Sie, welches Wort (a, b oder c) in die Lücken 21–30 passt.`
        : `Lesen Sie den folgenden Text zum Thema „${titleDe}“ und entscheiden Sie, welches Wort aus dem Kasten (A–O) in die Lücken 31–40 passt.`,
    introTextAr:
      part === 'SB1'
        ? `الجزء الأول من القواعد (Sprachbausteine Teil 1 — نقطتان: 15 نقطة، 1.5 لكل سؤال من 21 إلى 30): رسالة أو إيميل حول «${titleAr}».`
        : `الجزء الثاني من القواعد (Sprachbausteine Teil 2 — نقطتان: 15 نقطة، 1.5 لكل سؤال من 31 إلى 40): مقالة علمية/اجتماعية حول «${titleAr}».`,
    gaps,
  };
}

