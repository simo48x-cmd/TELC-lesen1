import { Teil2Topic, Teil2Question, Teil2Paragraph, VariantCodeInfo } from './lesenTypes';

interface RawTeil2QSpec {
  qDe: string;
  qAr: string;
  origAns: 'a' | 'b' | 'c';
  mod1Ans?: 'a' | 'b' | 'c';
  mod2Ans?: 'a' | 'b' | 'c';
  correctDe: string;
  correctAr: string;
  mod1CorrectDe?: string;
  mod1CorrectAr?: string;
  distractor1De: string;
  distractor1Ar: string;
  distractor2De: string;
  distractor2Ar: string;
  motCleDe: string;
  motCleAr: string;
  modAlertAr?: string;
  paragraphDe: string;
  paragraphAr: string;
}

function buildTeil2Topic(
  number: number,
  id: string,
  titleDe: string,
  titleAr: string,
  linkedWith: string,
  frequencyBadge: string,
  variants: VariantCodeInfo[],
  qSpecs: [RawTeil2QSpec, RawTeil2QSpec, RawTeil2QSpec, RawTeil2QSpec, RawTeil2QSpec]
): Teil2Topic {
  const paragraphs: Teil2Paragraph[] = qSpecs.map((q, idx) => ({
    titleDe: `Abschnitt ${idx + 1}`,
    german: q.paragraphDe,
    arabic: q.paragraphAr,
    highlightKeywords: [q.motCleDe, ...(q.mod1CorrectDe ? [q.mod1CorrectDe] : [])],
  }));

  const makeOptions = (
    targetLetter: 'a' | 'b' | 'c',
    cDe: string,
    cAr: string,
    d1De: string,
    d1Ar: string,
    d2De: string,
    d2Ar: string
  ) => {
    const letters: ('a' | 'b' | 'c')[] = ['a', 'b', 'c'];
    const distractors = [
      { german: d1De, arabic: d1Ar },
      { german: d2De, arabic: d2Ar },
    ];
    let dIdx = 0;
    return letters.map((letter) => {
      if (letter === targetLetter) {
        return { letter, german: cDe, arabic: cAr };
      }
      const d = distractors[dIdx++];
      return { letter, german: d.german, arabic: d.arabic };
    });
  };

  const questions: Teil2Question[] = qSpecs.map((q, idx) => {
    const qNum = idx + 6;
    const correctMap: Record<string, 'a' | 'b' | 'c'> = {
      original: q.origAns,
    };
    const optionsMap: Record<string, ReturnType<typeof makeOptions>> = {
      original: makeOptions(
        q.origAns,
        q.correctDe,
        q.correctAr,
        q.distractor1De,
        q.distractor1Ar,
        q.distractor2De,
        q.distractor2Ar
      ),
    };

    if (q.mod1Ans) {
      correctMap.mod1 = q.mod1Ans;
      optionsMap.mod1 = makeOptions(
        q.mod1Ans,
        q.mod1CorrectDe || q.correctDe,
        q.mod1CorrectAr || q.correctAr,
        q.distractor1De,
        q.distractor1Ar,
        q.distractor2De,
        q.distractor2Ar
      );
    }

    if (q.mod2Ans) {
      correctMap.mod2 = q.mod2Ans;
      optionsMap.mod2 = makeOptions(
        q.mod2Ans,
        q.mod1CorrectDe || q.correctDe,
        q.mod1CorrectAr || q.correctAr,
        q.distractor1De,
        q.distractor1Ar,
        q.distractor2De,
        q.distractor2Ar
      );
    }

    return {
      questionNumber: qNum,
      questionDe: q.qDe,
      questionAr: q.qAr,
      correctLetterByVariant: correctMap,
      optionsByVariant: optionsMap,
      motCleDe: q.motCleDe,
      motCleAr: q.motCleAr,
      modAlertAr: q.modAlertAr,
      explanationAr: `الموكلي الذهبي في الجواب الصحيح هو «${q.motCleDe}» (${q.motCleAr}). انتبه من الاختيارات الأخرى لأن فيها نفي (nicht / kein) أو عكس المعنى الموجود في النص.`,
    };
  });

  return {
    id,
    number,
    titleDe,
    titleAr,
    linkedWith,
    frequencyBadge,
    variants,
    paragraphs,
    questions,
  };
}

